// Validates curriculum JSON and writes review-flags.md (suspected source errors,
// missing answers, composed scene sentences) for teacher review.
//   node scripts/validate-content.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve('content/courses');
let errors = 0;
const err = (m) => { errors++; console.error('ERROR', m); };

for (const courseId of fs.readdirSync(root)) {
  const cdir = path.join(root, courseId);
  const course = JSON.parse(fs.readFileSync(path.join(cdir, 'course.json'), 'utf8'));
  const ids = new Map();
  const flags = [];
  const stats = { lessons: 0, exercises: 0, items: 0, vocab: 0, dialogues: 0, images: 0, noAnswer: 0 };
  const seen = (id, where) => {
    if (!id) return err(`${where}: missing id`);
    if (ids.has(id) && ids.get(id) !== where) err(`duplicate id ${id} (${ids.get(id)} / ${where})`);
    ids.set(id, where);
  };
  for (const f of course.chapters) {
    const ch = JSON.parse(fs.readFileSync(path.join(cdir, 'chapters', `${f}.json`), 'utf8'));
    for (const l of ch.lessons) {
      stats.lessons++;
      seen(l.id, `${f}/${l.id}`);
      if (!l.source?.designId) err(`${f}/${l.id}: lesson without source`);
      for (const b of l.blocks) {
        if (!b.source?.designId) err(`${f}/${l.id}: ${b.type} block without source`);
        if (b.type === 'vocab') stats.vocab += b.items.length;
        if (b.type === 'dialogue') stats.dialogues++;
        if (b.type === 'image') stats.images++;
        if (b.type === 'exercise') {
          stats.exercises++;
          seen(b.id, `${f}/${b.id}`);
          if (!b.exerciseType) err(`${b.id}: missing exerciseType`);
          for (const it of b.items) {
            stats.items++;
            seen(it.id, `${f}/${b.id}/${it.id}`);
            const blanks = (it.segments ?? []).filter((s) => s.blank).length;
            const tblanks = (it.translitSegments ?? []).filter((s) => s.blank).length;
            if (it.translitSegments && blanks !== tblanks) err(`${it.id}: Arabic has ${blanks} blanks, transliteration ${tblanks}`);
            if (!it.answers?.length && !it.model?.ar && !it.model?.en) stats.noAnswer++;
            for (const fl of it.flags ?? []) flags.push({ where: `${f} · ${b.title ?? b.id} · ${it.id}`, page: (it.source?.pages ?? [it.source?.page])[0], ...fl });
          }
        }
        for (const fl of b.flags ?? []) flags.push({ where: `${f} · ${l.title} · ${b.type}`, page: b.source?.pages?.[0], ...fl });
      }
    }
  }
  const scenesDir = path.join(cdir, 'scenes');
  if (fs.existsSync(scenesDir))
    for (const s of fs.readdirSync(scenesDir)) {
      const sc = JSON.parse(fs.readFileSync(path.join(scenesDir, s), 'utf8'));
      for (const r of sc.rooms)
        for (const t of r.tasks) {
          for (const k of ['targetId', 'objectId']) if (t[k] && !r.objects.some((o) => o.id === t[k])) err(`${s}/${t.id}: unknown ${k} ${t[k]}`);
          if (t.zoneId && !r.zones?.some((z) => z.id === t.zoneId)) err(`${s}/${t.id}: unknown zone`);
          for (const fl of t.flags ?? []) flags.push({ where: `scene ${sc.id} · ${r.en} · ${t.id}: ${t.model.ar}`, page: null, ...fl });
        }
    }
  console.log(courseId, stats);
  if (course.chapters.length) {
    const order = { 'suspected-error': 0, 'missing-answer': 1, ambiguous: 2, 'needs-review': 3 };
    flags.sort((a, b) => (order[a.kind] ?? 9) - (order[b.kind] ?? 9));
    const md = [`# Review flags — ${course.title}`, '', 'Generated by `npm run validate-content`. Nothing here was changed in the curriculum; each item awaits a teacher decision.', '', `Canonical source: Canva \`${course.canonicalSource?.designId}\` “${course.canonicalSource?.title}”.`, '', '| Kind | Page | Where | Note |', '|---|---|---|---|',
      ...flags.map((x) => `| ${x.kind} | ${x.page ?? ''} | ${x.where.replace(/\|/g, '/')} | ${(x.note ?? '').replace(/\|/g, '/').replace(/\n/g, ' ')} |`)];
    fs.writeFileSync(path.join(cdir, 'review-flags.md'), md.join('\n') + '\n');
    console.log(`${courseId}: ${flags.length} flags → content/courses/${courseId}/review-flags.md`);
  }
}
if (errors) { console.error(`${errors} error(s)`); process.exit(1); }
